"""Soft's outline icons (local fork): every tile icon of packages/core.yaml (`&tile_icons`) that Material Design Icons
also draws as `<name>-outline`, written as the firmware's table (components/smart_display/soft_icons.h) and as the glyphs
of Soft's outline icon fonts in packages/looks/shared/themes.yaml (between the markers), and the core's tile icons copied
there for Glow's icon font.

    python3 tools/soft_outlines.py          write both
    python3 tools/soft_outlines.py --check  exit 1 when either is out of date

Needs fontTools, as tools/generate_icons.py does.
"""
import argparse
import re
import sys
from pathlib import Path

from fontTools.ttLib import TTFont

REPO = Path(__file__).resolve().parents[1]
CORE = REPO / 'packages/core.yaml'
THEME = REPO / 'packages/looks/shared/themes.yaml'
HEADER = REPO / 'components/smart_display/soft_icons.h'
FONT = REPO / 'fonts/materialdesignicons-webfont.ttf'
BEGIN, END = '# BEGIN soft outlines (tools/soft_outlines.py)', '# END soft outlines'
ICONS_BEGIN, ICONS_END = '# BEGIN tile icons (tools/soft_outlines.py)', '# END tile icons'
# An "-outline" that says something else than its filled icon: an empty battery, not the same battery drawn in lines.
MEANS_ELSE = ('battery',)


def outlines():
    """[(name, filled codepoint, outline codepoint)] in the order of the core's tile icons."""
    core = CORE.read_text()
    block = core[core.index('glyphs: &tile_icons'):]
    block = block[:block.index('\n\n')]
    icons = re.findall(r'"\\U000([0-9A-F]{5})" # ([\w-]+)', block)
    cmap = TTFont(FONT).getBestCmap()
    by_name = {}
    for code, glyph in sorted(cmap.items()):
        by_name.setdefault(glyph, code)
    return [(name, int(code, 16), by_name[f'{name}-outline']) for code, name in icons
            if f'{name}-outline' in by_name and not name.startswith(MEANS_ELSE)]


def header(found):
    rows = '\n'.join(f'  {{0x{filled:05X}, 0x{outline:05X}}},  // {name}' for name, filled, outline in sorted(found, key=lambda f: f[1]))
    return f'''#pragma once
// GENERATED by tools/soft_outlines.py from packages/core.yaml and the MDI font: do not edit.
// Soft's outline icons (local fork): a tile icon and its "-outline" twin, by the filled icon's codepoint.
#include <cstdint>

namespace soft_icons {{
struct Outline {{ uint32_t filled, outline; }};
inline constexpr Outline OUTLINES[] = {{
{rows}
}};
inline constexpr unsigned COUNT = sizeof(OUTLINES) / sizeof(OUTLINES[0]);
// The outline twin of a filled icon's codepoint, or 0 when Material Design Icons draws none.
inline uint32_t outline_of(uint32_t filled) {{
  unsigned low = 0, high = COUNT;
  while (low < high) {{
    const unsigned mid = (low + high) / 2;
    if (OUTLINES[mid].filled < filled) low = mid + 1; else high = mid;
  }}
  return low < COUNT && OUTLINES[low].filled == filled ? OUTLINES[low].outline : 0;
}}
}}  // namespace soft_icons
'''


def tile_icons():
    """The core's tile icon glyph lines (`&tile_icons`), as written there."""
    core = CORE.read_text()
    block = core[core.index('glyphs: &tile_icons'):]
    return re.findall(r'^      - "\\U000[0-9A-F]{5}" # [\w-]+$', block[:block.index('\n\n')], re.M)


def between(text, begin, end, lines):
    start, stop = text.index(begin), text.index(end)
    return text[:start] + begin + '\n' + '\n'.join(lines) + '\n      ' + text[stop:]


def theme(found):
    text = THEME.read_text()
    glyphs = [f'      - "\\U000{outline:05X}" # {name}-outline' for name, _, outline in found]
    text = between(text, BEGIN, END, glyphs)
    # Glow's icon font carries the core's tile icons, copied here.
    return between(text, ICONS_BEGIN, ICONS_END, tile_icons())


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    found = outlines()
    wanted = {HEADER: header(found), THEME: theme(found)}
    stale = [path for path, text in wanted.items() if not path.exists() or path.read_text() != text]
    if args.check:
        for path in stale:
            print(f'{path.relative_to(REPO)} is out of date: run tools/soft_outlines.py')
        sys.exit(1 if stale else 0)
    for path in stale:
        path.write_text(wanted[path])
    print(f'{len(found)} outline icons; wrote {", ".join(str(p.relative_to(REPO)) for p in stale) or "nothing"}')


if __name__ == '__main__':
    main()
